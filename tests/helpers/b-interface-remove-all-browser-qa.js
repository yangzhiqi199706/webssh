async (page) => {
  await page.setExtraHTTPHeaders({}); await page.setViewportSize({ width: 1366, height: 900 });
  await page.goto('http://127.0.0.1:3037/proto-conv/index.html');
  await page.evaluate(() => fetch('/fixture/reset', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ count: 12, points: 4, enabled: true }) }));
  await page.getByRole('button', { name: 'B接口转发', exact: true }).click();
  await page.getByRole('tab', { name: '设备和测点', exact: true }).click();
  const remove = page.getByRole('button', { name: '移除全部设备', exact: true });
  if (await remove.count() !== 1) throw new Error('Missing remove-all device button');
  await page.locator('[data-bi-directory-device="4"]').uncheck();
  await page.locator('[data-bi-open-device="4"]').click();
  await page.locator('.bi-device').getByRole('textbox', { name: '设备资管编码', exact: true }).fill('保留未选设备');
  await page.locator('#biDeviceSearch').fill('无结果');
  await remove.click();
  await page.getByRole('alert').filter({ hasText: '已移除 11 个已勾选设备' }).waitFor();
  if (await page.locator('[data-bi-open-device]').count() !== 1 || !(await page.locator('.bi-device-meta').textContent()).includes('DCIM 4')) throw new Error('Removal missed hidden pages or removed unselected device');
  if (await page.locator('.bi-device').getByRole('textbox', { name: '设备资管编码', exact: true }).inputValue() !== '保留未选设备') throw new Error('Unselected draft changed');
  if (await page.locator('#biDeviceSearch').inputValue() !== '' || await remove.isEnabled()) throw new Error('Filter/no-selection state incorrect');
  if ((await page.evaluate(() => fetch('/fixture/saved').then(r => r.json()))).length) throw new Error('Remove automatically persisted configuration');
  await page.locator('#biSelectAllDevices').click(); await remove.click();
  await page.getByRole('heading', { name: '开始配置设备', exact: true }).waitFor();
  if (await page.locator('#biStatDevices').textContent() !== '0' || await page.locator('#biStatPoints').textContent() !== '0' || await remove.isEnabled()) throw new Error('Empty state not reset');
  if (await page.locator('#biDraftState').textContent() !== '有未保存修改') throw new Error('Dirty draft indicator missing');
  await page.locator('#biClose').click(); await page.getByRole('button', { name: 'B接口转发', exact: true }).click();
  await page.getByRole('tab', { name: '设备和测点', exact: true }).click();
  if (await page.locator('#biStatDevices').textContent() !== '12') throw new Error('Unsaved removal changed saved config');
  await remove.click(); await page.locator('#biSaveMapping').click();
  await page.getByRole('alert').filter({ hasText: '配置已保存' }).waitFor();
  const saved = await page.evaluate(() => fetch('/fixture/saved').then(r => r.json()));
  if (saved[saved.length - 1].devices.length !== 0) throw new Error('Save did not clear removed devices');
  if (saved[saved.length - 1].enabled !== false) throw new Error('Saving empty removed mapping must stop enabled forwarding');
  await page.setViewportSize({ width: 390, height: 844 }); await page.locator('#biSourceTools > summary').click();
  await remove.scrollIntoViewIfNeeded(); const box = await remove.boundingBox();
  if (!box || box.x < 0 || box.x + box.width > 390) throw new Error('Remove control overflows mobile');
  await page.screenshot({ path: 'output/playwright/b-interface-remove-all-mobile.png' });
  await page.locator('#biClose').click();
  await page.evaluate(() => fetch('/fixture/reset', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ count: 2, points: 4 }) }));
  await page.setExtraHTTPHeaders({ 'X-Fixture-Role': 'viewer' }); await page.getByRole('button', { name: 'B接口转发', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: '只读' }).waitFor(); await page.getByRole('tab', { name: '设备和测点', exact: true }).click();
  if (await remove.isEnabled()) throw new Error('Viewer can remove devices');
  return 'PASS selected-only removal across pages/search, unselected drafts preserved, no auto-save, reopen restores, saved empty config, mobile and viewer';
}
